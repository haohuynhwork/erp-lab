package com.erplab.auth.domain;

import static com.erplab.common.security.Permissions.*;

import java.util.Set;

/** Part of the commands interface: used in CreateUser. */
@org.springframework.modulith.NamedInterface("commands")
public enum Role {

	ADMIN(USERS_MANAGE, MASTERDATA_READ, MASTERDATA_WRITE, INVENTORY_READ, INVENTORY_WRITE, PURCHASING_READ,
			PURCHASING_WRITE, SALES_READ, SALES_WRITE, ACCOUNTING_READ, ACCOUNTING_WRITE, REPORTS_READ),
	MANAGER(MASTERDATA_READ, INVENTORY_READ, PURCHASING_READ, SALES_READ, ACCOUNTING_READ, REPORTS_READ),
	SALES(MASTERDATA_READ, INVENTORY_READ, SALES_READ, SALES_WRITE, REPORTS_READ),
	PURCHASING(MASTERDATA_READ, MASTERDATA_WRITE, INVENTORY_READ, PURCHASING_READ, PURCHASING_WRITE),
	WAREHOUSE(MASTERDATA_READ, INVENTORY_READ, INVENTORY_WRITE, PURCHASING_READ, SALES_READ),
	ACCOUNTANT(MASTERDATA_READ, SALES_READ, PURCHASING_READ, ACCOUNTING_READ, ACCOUNTING_WRITE, REPORTS_READ);

	private final Set<String> permissions;

	Role(String... permissions) {
		this.permissions = Set.of(permissions);
	}

	public Set<String> permissions() {
		return permissions;
	}

}
